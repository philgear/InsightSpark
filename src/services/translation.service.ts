@Injectable({
  providedIn: 'root'
})
export class TranslationService {
  private readonly LANG_STORAGE_KEY = 'spark_lang_val';
  
  // Reactive current language signal
  currentLang = signal<string>(this.getInitialLanguage());

  // Current dictionary computed signal
  currentDict = computed(() => {
    const lang = this.currentLang();
    return TRANSLATIONS[lang] || TRANSLATIONS['en'];
  });

  // Expose supported languages list
  readonly supportedLanguages = SUPPORTED_LANGUAGES_LIST;

  private getInitialLanguage(): string {
    const stored = localStorage.getItem(this.LANG_STORAGE_KEY) || localStorage.getItem('user_target_language');
    if (stored) return stored;
    
    // Auto-detect browser language if supported
    const navLang = navigator.language?.split('-')[0]?.toLowerCase();
    if (navLang && SUPPORTED_LANGUAGES_LIST.some(l => l.code === navLang)) {
      return navLang;
    }
    return 'en';
  }

  setLanguage(code: string): void {
    this.currentLang.set(code);
    localStorage.setItem(this.LANG_STORAGE_KEY, code);
    localStorage.setItem('user_target_language', code);
  }

  /**
   * Translate a key with fallback to English or the key itself.
   */
  t(key: string): string {
    const dict = this.currentDict();
    if (dict && dict[key]) {
      return dict[key];
    }
    const enDict = TRANSLATIONS['en'];
    if (enDict && enDict[key]) {
      return enDict[key];
    }
    return key;
  }

  getLanguageInfo(code: string): LanguageInfo | undefined {
    return this.supportedLanguages.find(l => l.code === code);
  }
}
